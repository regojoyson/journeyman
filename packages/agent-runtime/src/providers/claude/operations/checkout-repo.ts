import { query } from "@anthropic-ai/claude-agent-sdk";
import { createLogger } from "@journeyman/core";
import { logSdkMessage } from "../utils/sdk-logger.ts";
import { resolveSession } from "../utils/session.ts";
import { confinementSystemPrompt } from "../../../workspace-guard/index.ts";
import { buildWorkspaceHook } from "../utils/workspace-hook.ts";
import type { CheckoutEntry, CheckoutRepoOptions, CheckoutRepoResult } from "@journeyman/core";

const log = createLogger("claude:checkout-repo");

export type { CheckoutEntry, CheckoutRepoOptions, CheckoutRepoResult };

const OUTPUT_SCHEMA = {
  type: "object",
  properties: {
    newBranch: { type: "string" },
    repos: {
      type: "array",
      items: {
        type: "object",
        properties: {
          folderName: { type: "string" },
          repoDir: { type: "string" },
          baseBranch: { type: "string" },
          newBranch: { type: "string" },
          success: { type: "boolean" },
          error: { type: "string" },
        },
        required: ["folderName", "repoDir", "baseBranch", "newBranch", "success"],
      },
    },
    error: { type: "string" },
  },
  required: ["newBranch", "repos"],
} as const;

function normalizeEntries(opts: CheckoutRepoOptions): CheckoutEntry[] {
  const raw = Array.isArray(opts.repos) ? opts.repos : [opts.repos];
  return raw.map((r) =>
    typeof r === "string" ? { repoDir: r, branch: opts.branch ?? "main" } : r
  );
}

function buildPrompt(
  entries: CheckoutEntry[],
  issue: CheckoutRepoOptions["issue"],
): string {
  const steps = entries
    .map(({ repoDir, branch }) => `  - ${repoDir} → baseBranch: ${branch}`)
    .join("\n");

  const namingRule = issue
    ? [
        "BRANCH NAMING (issue provided):",
        `  Format: "{id-lowercased}/{2-4-word-slug}_{unix-seconds}"`,
        `  Issue id: ${issue.id}`,
        `  Issue title: ${issue.title}`,
        `  Slug: lowercase ASCII, hyphen-separated, 2-4 meaningful words from the title`,
        `         (strip stopwords like "the", "a", "an", "on", "for", "to", "of", "and").`,
        `  Example: id "EV-12345", title "Fix header alignment bug on checkout page"`,
        `           → "ev-12345/fix-header-alignment_1713542400"`,
      ].join("\n")
    : [
        "BRANCH NAMING (no issue):",
        `  Format: "{animal-themed-slug}_{unix-seconds}"`,
        `  Slug: lowercase ASCII, hyphen-separated, 2-3 words containing one animal name`,
        `         (e.g. "curious-otter-sprint", "swift-falcon-work").`,
      ].join("\n");

  return [
    "You will sync local repos to origin, then create ONE new feature branch used across all repos.",
    "",
    namingRule,
    "",
    "  - Before touching any repo, run `date +%s` ONCE to get the current unix-seconds timestamp.",
    "  - Use that single timestamp value in the branch name for ALL repos. Do NOT re-run `date` inside the per-repo loop.",
    "  - The EXACT same branch name must be used for every repo.",
    "",
    "PER-REPO STEPS (run in order for each repo):",
    "  1. git -C <repoDir> fetch origin",
    "  2. git -C <repoDir> stash --include-untracked   (discard local changes)",
    "  3. git -C <repoDir> checkout <baseBranch>",
    "  4. git -C <repoDir> pull origin <baseBranch>",
    "  5. git -C <repoDir> reset --hard origin/<baseBranch>",
    "  6. git -C <repoDir> clean -fd",
    "  7. git -C <repoDir> checkout -b <newBranch>",
    "",
    "Repos:",
    steps,
    "",
    "Return JSON with:",
    "  - newBranch (top-level): the generated branch name used for all repos",
    "  - repos[]: { folderName, repoDir, baseBranch, newBranch, success, error? }",
    "  - error (top-level, optional): set only if everything failed before per-repo work started",
    "Capture per-repo errors in repos[].error and set success=false for that repo.",
  ].join("\n");
}

/**
 * Hard-resets each repo's base branch to match origin, then creates ONE new
 * feature branch (used across all repos). Branch name is generated by Claude
 * from issue details when provided, or as an animal-themed fallback.
 *
 * @param opts - Repos, base branch, and optional issue driving the branch name.
 * @returns A CheckoutRepoResult with the generated newBranch and per-repo details.
 *
 * @example
 * ```ts
 * const result = await checkoutRepo({
 *   repos: [
 *     { repoDir: "/projects/api", branch: "main" },
 *     { repoDir: "/projects/web", branch: "main" },
 *   ],
 *   issue: { id: "EV-12345", title: "Fix header alignment on checkout" },
 * });
 * console.log(result.newBranch); // e.g. "ev-12345/fix-header-alignment_1713542400"
 * ```
 */
export async function checkoutRepo(opts: CheckoutRepoOptions): Promise<CheckoutRepoResult> {
  const entries = normalizeEntries(opts);
  const { sessionId, queryOption } = resolveSession(opts.sessionId);
  log.info(
    { sessionId, repoCount: entries.length, ref: opts.issue?.id },
    "checkoutRepo start",
  );
  if (entries.length === 0) {
    log.warn({ sessionId }, "checkoutRepo called with no repos");
    return { repos: [], newBranch: "", sessionId };
  }
  const controller = opts.signal
    ? (() => {
        const ac = new AbortController();
        if (opts.signal!.aborted) ac.abort(opts.signal!.reason);
        else opts.signal!.addEventListener("abort", () => ac.abort(opts.signal!.reason), { once: true });
        return ac;
      })()
    : undefined;
  const root = opts.cwd ?? entries[0]?.repoDir ?? process.cwd();
  const prompt = [confinementSystemPrompt(root), buildPrompt(entries, opts.issue)].join("\n\n");
  let output: CheckoutRepoResult = { repos: [], newBranch: "", sessionId };

  for await (const msg of query({
    prompt,
    options: {
      tools: ["Bash"],
      allowedTools: ["Bash"],
      permissionMode: "bypassPermissions",
      allowDangerouslySkipPermissions: true,
      maxTurns: 40,
      settingSources: [],
      settings: { allowedMcpServers: [] },
      outputFormat: { type: "json_schema", schema: OUTPUT_SCHEMA },
      additionalDirectories: [],
      hooks: buildWorkspaceHook(root),
      ...(opts.model ? { model: opts.model } : {}),
      ...(controller !== undefined ? { abortController: controller } : {}),
      ...queryOption,
    },
  })) {
    logSdkMessage(msg, opts.onLog, opts.agentLogLevel ?? "all");
    if (msg.type === "result") {
      if (msg.subtype !== "success") {
        const error = (msg as any).errors?.[0] ?? msg.subtype;
        log.error({ sessionId, error }, "checkoutRepo failed");
        return { repos: [], newBranch: "", error, sessionId };
      }
      output = { ...(msg.structured_output as CheckoutRepoResult), sessionId };
    }
  }

  log.info(
    {
      sessionId,
      newBranch: output.newBranch,
      successCount: output.repos.filter((r) => r.success).length,
      failureCount: output.repos.filter((r) => !r.success).length,
    },
    "checkoutRepo done",
  );
  return output;
}


